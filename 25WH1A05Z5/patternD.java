package z5;



public class pattern5 {



	public static void main(String[] args) {

      for(int i=1;i<7;i++) {

    	  for(int j=1;j<i;j++) {

    		  System.out.print(" ");

    	  }

    	  for(char k='A';k<'H'-i;k++) {

    		  System.out.print(k);

    	  }

    	  System.out.println();

      }

	}



}
